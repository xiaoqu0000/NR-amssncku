        double v9=fma(0x1.a617627a8eb10p-3,r,-0x1.ec709da475e58p-3);
        const double r2=mul(r,r);
        double v11=fma(0x1.ec709dc3a03fdp-2,r,-0x1.71547652b82fep-1);
        v5=sub(v5,lh);
        v9=fma(r2,v6a,v9);
        v11=fma(r2,v8,v11);
        double v6=mul(r2,r2);
        v6=fma(v6,v9,v11);
        v5=fma(v7,r,v5);
        v4=add(v4,v5);
        ll=fma(r2,v6,v4);
    } else {
        const double v2a=add(exponent,number(log_table[idx+2]));
        const double v4a=0x1.71547652b82fep+0;
        const double v5a=fma(v4a,r,v2a);
        const double v6a=fma(0x1.48569ebc938ecp-3,r,-0x1.715ed9b489989p-3);
