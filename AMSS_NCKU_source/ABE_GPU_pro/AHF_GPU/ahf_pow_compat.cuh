T219_HD std::uint64_t bits(double x) {
#if defined(__CUDA_ARCH__)
    return static_cast<std::uint64_t>(__double_as_longlong(x));
#else
    std::uint64_t v; std::memcpy(&v,&x,8); return v;
#endif
}
T219_HD double number(std::uint64_t v) {
#if defined(__CUDA_ARCH__)
    return __longlong_as_double(static_cast<long long>(v));
#else
    double x; std::memcpy(&x,&v,8); return x;
#endif
}
