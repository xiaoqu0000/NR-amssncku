        double v11=sub(v2a,v5a);
        const double v12=-0x1.71547652b82fep-1;
        lh=fma(v12,r2,v5a);
        v9=fma(r2,v6a,v9);
        v10=fma(r2,v8,v10);
        v11=fma(r,v4a,v11);
