}
T219_HD Result pow_compat(double x,double y) {
    const auto xb=bits(x);
    if (!(xb>0 && xb<0x7ff0000000000000ULL)) return fail(Status::unsupported_input,0);
    if (!(y==-0.25 || y==-1.25 || y==0.5)) return fail(Status::unsupported_exponent,0);
    const std::uint32_t lo=static_cast<std::uint32_t>(xb),hi=static_cast<std::uint32_t>(xb>>32);
    const std::uint32_t alo=lo+0x0U, edx=hi+0xc0101000U;
    std::uint32_t eax=sar(edx,11);
    const bool near=(eax+0xfeU)<0x201U;
    if (!near && (eax-0x80002U)<0xfff00400U) return fail(Status::unsupported_e7_input,0);
    const auto reduced=std::uint64_t(lo-(alo&0x0U)) | (std::uint64_t(hi-(edx&0xfff00000U))<<32);
    const unsigned idx=eax&0x1fcU;
    double r=fma(number(log_table[idx]),number(reduced),-0x1.0000000000000p+0);
    const double exponent=signed32double(sar(edx,20));
    double lh,ll;
    if (!near) {
        double v5=add(exponent,number(log_table[idx+2]));
        double v4=fma(0x1.777d1083f2b10p-56,r,number(log_table[idx+3]));
        const double v6a=fma(0x1.48569ebc938ecp-3,r,-0x1.715ed9b489989p-3);
        const double v7=0x1.71547652b82fep+0;
