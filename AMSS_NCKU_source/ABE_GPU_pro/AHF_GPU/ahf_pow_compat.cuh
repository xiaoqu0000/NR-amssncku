T219_HD double ftz(double x) {
    const auto u=bits(x);
    return (u&0x7ff0000000000000ULL)==0 ? number(u&0x8000000000000000ULL) : x;
}
T219_HD std::uint32_t sar(std::uint32_t v,unsigned n) {
    return (v>>n)|((0U-(v>>31))<<(32-n));
}
T219_HD double signed32double(std::uint32_t v) {
    return v<0x80000000U ? static_cast<double>(v) : -static_cast<double>(0x100000000ULL-v);
}
